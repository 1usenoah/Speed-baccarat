import { chromium } from 'playwright';
const BASE = 'https://1usenoah.github.io/Speed-baccarat/';
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const b = await chromium.launch({ executablePath: '/workspace/.cache/ms-playwright/chromium-1255/chrome-linux64/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await b.newContext({ viewport: { width: 1280, height: 860 } });
await ctx.addInitScript(() => { localStorage.setItem('evolab.session.v1', JSON.stringify({ username: 'v2shot7066883' })); });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto(BASE, { waitUntil: 'load' });
await wait(3000);
await page.click('.lobby-card');
await wait(1500);
const before = await page.evaluate(() => window.__SB.state().balance);
await page.click('#view-baccarat .zone[data-zone="P"]');
await wait(400);
await page.click('#view-baccarat .zone[data-zone="B"]');
await wait(400);
const after = await page.evaluate(() => ({ bal: window.__SB.state().balance, bet: window.__SB.state().bet }));
console.log('balance', before, '->', JSON.stringify(after), 'errors', errs.length, errs.slice(0, 3));
await page.screenshot({ path: '/workspace/downloads/speed-baccarat-v2/live_09_bet_placed.png' });
await b.close();
process.exit(0);
