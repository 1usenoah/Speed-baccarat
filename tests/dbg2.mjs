import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
const PORT=5199, BASE=`http://127.0.0.1:${PORT}/Speed-baccarat/`;
const pv = spawn(process.execPath,['node_modules/vite/bin/vite.js','preview','--port',String(PORT),'--strictPort','--host','127.0.0.1'],{cwd:'/workspace/projects/speed-baccarat',stdio:'ignore'});
const wait=(ms)=>new Promise(r=>setTimeout(r,ms));
for(let i=0;i<40;i++){try{if((await fetch(BASE)).ok)break;}catch(e){}await wait(250);}
const b = await chromium.launch({executablePath:'/workspace/.cache/ms-playwright/chromium-1255/chrome-linux64/chrome',args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-background-timer-throttling','--disable-renderer-backgrounding','--disable-backgrounding-occluded-windows','--disable-features=CalculateNativeWinOcclusion']});
const ctx = await b.newContext({viewport:{width:1440,height:900}});
const page = await ctx.newPage();
page.on('console',m=>{if(m.type()==='error')console.log('CONSOLE ERR',m.text())});
page.on('pageerror',e=>console.log('PAGEERROR',e.message));
await page.goto(BASE,{waitUntil:'load'});
await wait(1500);
await page.click('.auth-tabs button[data-mode="signup"]');
await page.fill('#authUser','z'+String(Date.now()).slice(-7));
await page.fill('#authPass','pass1234');
await page.fill('#authPass2','pass1234');
await page.click('.auth-submit');
await wait(1500);
console.log('modal closed?', await page.evaluate(()=>!document.querySelector('.modal-backdrop')));
await page.click('.lobby-card[data-table="speed-a"]');
await page.waitForFunction(()=>{const s=window.__SB.state();return s.phase==='betting'&&s.timeLeft>6500;},null,{timeout:40000});
console.log('zones', await page.evaluate(()=>Array.from(document.querySelectorAll('#view-baccarat [data-zone]')).map(e=>e.dataset.zone+':'+e.className)));
console.log('click P');
await page.click('#chipTray .chip[data-value="25000"]');
await page.click('#view-baccarat .zone[data-zone="P"]');
await wait(400);
console.log('after P zones', await page.evaluate(()=>document.querySelectorAll('#view-baccarat [data-zone]').length));
console.log('state', await page.evaluate(()=>window.__SB.state()));
console.log('modal?', await page.evaluate(()=>document.querySelector('#modalRoot')?.innerText?.slice(0,60)));
await b.close(); pv.kill('SIGKILL'); process.exit(0);
